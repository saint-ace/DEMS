"""
Digital Evidence Management System (DEMS)

Module:
    Reports

File:
    pdf.py

Purpose:
    Generate PDF reports.
"""

from io import BytesIO

from reportlab.lib.units import inch
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
)
from reportlab.lib.styles import getSampleStyleSheet
class PDFReportGenerator:
    """
    Generates PDF reports.
    """

    @staticmethod
    def generate(report):
        """
        Generate a PDF for a report.

        Returns:
            BytesIO
        """

        buffer = BytesIO()

        document = SimpleDocTemplate(
            buffer,
            rightMargin=0.75 * inch,
            leftMargin=0.75 * inch,
            topMargin=0.75 * inch,
            bottomMargin=0.75 * inch,
        )

        styles = getSampleStyleSheet()

        story = []
        story.append(
            Paragraph(
                "Digital Evidence Management System",
                styles["Title"],
            )
        )

        story.append(
            Spacer(
                1,
                0.3 * inch,
            )
        )
        story.append(
            Paragraph(
                f"<b>Report Number:</b> {report.report_number}",
                styles["Normal"],
            )
        )

        story.append(
            Paragraph(
                f"<b>Title:</b> {report.title}",
                styles["Normal"],
            )
        )

        story.append(
            Paragraph(
                f"<b>Type:</b> {report.get_report_type_display()}",
                styles["Normal"],
            )
        )

        story.append(
            Paragraph(
                f"<b>Status:</b> {report.get_status_display()}",
                styles["Normal"],
            )
        )

        story.append(
            Paragraph(
                f"<b>Generated By:</b> {report.generated_by.username}",
                styles["Normal"],
            )
        )

        story.append(
            Paragraph(
                f"<b>Generated At:</b> {report.generated_at}",
                styles["Normal"],
            )
        )

        story.append(
            Spacer(
                1,
                0.25 * inch,
            )
        )
        story.append(
            Paragraph(
                "<b>Notes</b>",
                styles["Heading2"],
            )
        )

        story.append(
            Paragraph(
                report.notes or "No notes provided.",
                styles["BodyText"],
            )
        )
        document.build(story)

        buffer.seek(0)

        return buffer